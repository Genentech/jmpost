#' @rdname longitudinal_model_stan_data
#' @keywords internal
#' @export
longitudinal_model_stan_data.LongitudinalSteinFojoCov <- function(model, subject) {
    subject_data <- as.data.frame(harmonise(subject))
    parameter_names <- c("mu_b", "omega_b", "mu_s", "omega_s", "mu_g", "omega_g")
    designs <- lapply(parameter_names, function(name) {
        .covariate_design_matrix(
            slot(model, paste0(name, "_formula")),
            subject_data,
            paste0(name, "_formula")
        )
    })
    names(designs) <- parameter_names
    result <- list()
    for (name in parameter_names) {
        result[[paste0("p_lm_sfc_", name)]] <- ncol(designs[[name]])
        result[[paste0("lm_sfc_", name, "_design")]] <- designs[[name]]
    }
    result
}

#' @rdname required_longitudinal_covs
#' @export
required_longitudinal_covs.LongitudinalSteinFojoCov <- function(object, ...) {
    unique(unlist(lapply(c("mu_b", "mu_s", "mu_g"), function(name) {
        all.vars(slot(object, paste0(name, "_formula")))
    })))
}

#' @rdname required_simulation_covariates
#' @export
required_simulation_covariates.LongitudinalSteinFojoCov <- function(
    object,
    ...
) {
    unique(unlist(lapply(
        c("mu_b", "omega_b", "mu_s", "omega_s", "mu_g", "omega_g"),
        function(name) all.vars(slot(object, paste0(name, "_formula")))
    )))
}

#' Create covariate Stein-Fojo population-prediction Stan data
#'
#' @keywords internal
#' @returns A named list of population generated-quantities design matrices.
.stein_fojo_cov_population_stan_data <- function(model, subject, newdata) {
    subject_data <- as.data.frame(harmonise(subject))
    parameter_names <- c("mu_b", "mu_s", "mu_g")
    result <- lapply(parameter_names, function(name) {
        .covariate_prediction_design_matrix(
            slot(model, paste0(name, "_formula")),
            newdata,
            subject_data,
            paste0(name, "_formula")
        )
    })
    names(result) <- paste0("gq_lm_sfc_", parameter_names, "_design")
    result
}
